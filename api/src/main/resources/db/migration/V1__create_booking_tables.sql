-- Flyway owns the schema. JPA must validate it rather than create or update it.
CREATE TABLE venues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    location VARCHAR(200) NOT NULL,
    capacity INTEGER NOT NULL,
    open_time TIME WITHOUT TIME ZONE NOT NULL,
    close_time TIME WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN',

    CONSTRAINT pk_venues PRIMARY KEY (id),
    CONSTRAINT ck_venues_name_not_blank CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT ck_venues_location_not_blank CHECK (location ~ '[^[:space:]]'),
    CONSTRAINT ck_venues_capacity_positive CHECK (capacity > 0),
    CONSTRAINT ck_venues_time_order CHECK (open_time < close_time),
    CONSTRAINT ck_venues_status CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    venue_id BIGINT NOT NULL,
    booked_by VARCHAR(100) NOT NULL,
    reservation_date DATE NOT NULL,
    start_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE NOT NULL,
    attendee_count INTEGER NOT NULL,
    purpose VARCHAR(500) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_reservations PRIMARY KEY (id),
    CONSTRAINT fk_reservations_venue FOREIGN KEY (venue_id) REFERENCES venues (id),
    CONSTRAINT ck_reservations_booked_by_not_blank CHECK (booked_by ~ '[^[:space:]]'),
    CONSTRAINT ck_reservations_purpose_not_blank CHECK (purpose ~ '[^[:space:]]'),
    CONSTRAINT ck_reservations_attendee_count_positive CHECK (attendee_count > 0),
    CONSTRAINT ck_reservations_time_order CHECK (start_time < end_time),
    CONSTRAINT ck_reservations_status CHECK (status IN ('ACTIVE', 'CANCELLED')),
    CONSTRAINT ck_reservations_cancelled_at CHECK (
        (status = 'ACTIVE' AND cancelled_at IS NULL)
        OR (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
    )
);

-- This index supports conflict queries; the API must also lock the venue row
-- inside its transaction before checking conflicts and inserting a reservation.
CREATE INDEX idx_reservations_conflict
    ON reservations (venue_id, reservation_date, status, start_time, end_time);
